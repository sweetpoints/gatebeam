func TestCARoleRejectsMembershipAdministration(t *testing.T) {
	f := newCARoleFixture(t)
	f.exec(t, "ALTER TABLE pki_issuers OWNER TO "+f.alternate)
	f.exec(t, "REVOKE UPDATE,DELETE,TRUNCATE ON pki_issuers FROM "+f.alternate)
	f.exec(t, "GRANT "+f.alternate+" TO "+f.role+" WITH ADMIN TRUE, INHERIT FALSE, SET FALSE")
	accepted := CheckCARole(f.ctx, f.login) == nil
	// ADMIN can change membership options; existing SET FALSE is not a boundary.
	f.asLogin(t, "GRANT "+f.alternate+" TO "+f.role+" WITH SET TRUE")
	f.asLogin(t, "SET ROLE "+f.alternate)
	f.asLogin(t, "GRANT UPDATE ON pki_issuers TO "+f.alternate)
	f.asLogin(t, "RESET ROLE")
	if accepted {
		t.Fatal("membership administrator accepted before self-enabling owner SET ROLE")
	}
}
