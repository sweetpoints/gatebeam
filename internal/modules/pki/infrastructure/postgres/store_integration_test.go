// Each case uses a fresh schema and real non-superuser login. Role/catalog
// changes affect only names generated by this fixture and are reverted on exit.
type caRoleFixture struct {
	admin, login                    *pgxpool.Pool
	ctx                             context.Context
	role, alternate, bridge, schema string
}

func newCARoleFixture(t *testing.T) *caRoleFixture {
	t.Helper()
	admin := testkit.Postgres(t)
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	t.Cleanup(cancel)
	nonce := make([]byte, 8)
	if _, e := rand.Read(nonce); e != nil {
		t.Fatal(e)
	}
	role := "pki_gate_" + hex.EncodeToString(nonce)
	f := &caRoleFixture{admin: admin, ctx: ctx, role: role, alternate: role + "_alt", bridge: role + "_bridge"}
	if e := admin.QueryRow(ctx, "SELECT current_schema()").Scan(&f.schema); e != nil {
		t.Fatal(e)
	}
	for _, name := range []string{f.role, f.alternate, f.bridge} {
		f.exec(t, "CREATE ROLE "+pgx.Identifier{name}.Sanitize()+" LOGIN PASSWORD 'test-only'")
	}
	t.Cleanup(func() {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		for _, name := range []string{f.role, f.alternate, f.bridge} {
			q := pgx.Identifier{name}.Sanitize()
			for _, sql := range []string{"REASSIGN OWNED BY " + q + " TO CURRENT_USER", "DROP OWNED BY " + q, "DROP ROLE " + q} {
				if _, e := admin.Exec(ctx, sql); e != nil {
					t.Error(e)
				}
			}
		}
	})
	f.exec(t, "GRANT USAGE ON SCHEMA "+pgx.Identifier{f.schema}.Sanitize()+" TO "+f.role+","+f.alternate+","+f.bridge)
	f.exec(t, "GRANT SELECT,INSERT ON pki_issuers TO "+f.role+";GRANT UPDATE(key_fingerprint) ON pki_issuers TO "+f.role)
	f.exec(t, "GRANT INSERT ON pki_serial_reservations TO "+f.role)
	f.exec(t, "GRANT SELECT ON pki_restore_quarantine TO "+f.role)
	f.exec(t, "GRANT SELECT,INSERT ON pki_revocations,pki_status_certificates,pki_crl_versions TO "+f.role)
	f.exec(t, "GRANT UPDATE(number) ON pki_crl_versions TO "+f.role)
	f.exec(t, "GRANT SELECT,INSERT ON pki_root_crl_state TO "+f.role)
	f.exec(t, "GRANT UPDATE(number,der,revoked_serials) ON pki_root_crl_state TO "+f.role)
	f.exec(t, "GRANT SELECT,INSERT ON pki_orders,pki_certificates TO "+f.role)
	cfg := admin.Config().Copy()
	cfg.ConnConfig.User = f.role
	cfg.ConnConfig.Password = "test-only"
	cfg.MaxConns = 1
	var e error
	f.login, e = pgxpool.NewWithConfig(ctx, cfg)
	if e != nil {
		t.Fatal(e)
	}
	t.Cleanup(f.login.Close)
	var actual string
	if e = f.login.QueryRow(ctx, "SELECT session_user").Scan(&actual); e != nil || actual != f.role {
		t.Fatal("fixture did not connect as restricted login", e)
	}
	return f
}
func (f *caRoleFixture) exec(t *testing.T, sql string) {
	t.Helper()
	if _, e := f.admin.Exec(f.ctx, sql); e != nil {
		t.Fatal(e)
	}
}
func (f *caRoleFixture) asLogin(t *testing.T, sql string) {
	t.Helper()
	if _, e := f.login.Exec(f.ctx, sql); e != nil {
		t.Fatal(e)
	}
}
func (f *caRoleFixture) rejected(t *testing.T) {
	t.Helper()
	if e := CheckCARole(f.ctx, f.login); e == nil {
		t.Fatal("mutable or privileged CA capability accepted")
	}
}

func TestCARoleAcceptsRestrictedLoginAndAppendOnlyMembership(t *testing.T) {
	f := newCARoleFixture(t)
	if e := CheckCARole(f.ctx, f.login); e != nil {
		t.Fatal("ordinary restricted login rejected", e)
	}
	f.exec(t, "REVOKE SELECT,INSERT ON pki_issuers FROM "+f.role)
	f.exec(t, "REVOKE INSERT ON pki_serial_reservations FROM "+f.role)
	f.exec(t, "GRANT SELECT,INSERT ON pki_issuers TO "+f.alternate)
	f.exec(t, "GRANT INSERT ON pki_serial_reservations TO "+f.alternate)
	f.exec(t, "GRANT "+f.alternate+" TO "+f.role+" WITH INHERIT TRUE, SET TRUE")
	if e := CheckCARole(f.ctx, f.login); e != nil {
		t.Fatal("append-only capability membership rejected", e)
	}
}
func TestCARoleRejectsColumnUpdate(t *testing.T) {
	for _, tc := range []struct{ name, grant, mutation string }{
		{"issuer_der", "UPDATE(certificate_der) ON pki_issuers", "UPDATE pki_issuers SET certificate_der='replacement'::bytea"},
		{"serial", "UPDATE(serial) ON pki_serial_reservations", "UPDATE pki_serial_reservations SET serial=repeat('2',40)"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := newCARoleFixture(t)
			f.exec(t, "INSERT INTO pki_issuers(id,fingerprint,certificate_der,not_before,not_after) VALUES('owned','owned','public',now(),now()+interval '1 day')")
			f.exec(t, "INSERT INTO pki_serial_reservations(issuer_id,serial) VALUES('owned',repeat('1',40))")
			f.exec(t, "GRANT "+tc.grant+" TO "+f.role)
			f.asLogin(t, tc.mutation) // Prove this is real mutation authority, not just a grant.
			f.rejected(t)
		})
	}
}
func TestCARoleRejectsSelfRevokedNonSuperuserOwner(t *testing.T) {
	for _, table := range []string{"pki_issuers", "pki_serial_reservations"} {
		t.Run(table, func(t *testing.T) {
			f := newCARoleFixture(t)
			f.exec(t, "ALTER TABLE "+table+" OWNER TO "+f.role)
			f.asLogin(t, "REVOKE UPDATE,DELETE,TRUNCATE ON "+table+" FROM "+f.role)
			// Owner retains grant options even though ordinary DML was self-revoked.
			f.asLogin(t, "GRANT UPDATE ON "+table+" TO "+f.role)
			f.asLogin(t, "REVOKE UPDATE ON "+table+" FROM "+f.role)
			f.rejected(t)
		})
	}
}
func TestCARoleRejectsReachableAndInheritedOwners(t *testing.T) {
	for _, tc := range []struct{ name, options string }{
		{"set_only", "INHERIT FALSE, SET TRUE"},
		{"inherit_only", "INHERIT TRUE, SET FALSE"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := newCARoleFixture(t)
			f.exec(t, "ALTER TABLE pki_issuers OWNER TO "+f.alternate)
			f.exec(t, "REVOKE UPDATE,DELETE,TRUNCATE ON pki_issuers FROM "+f.alternate)
			f.exec(t, "GRANT "+f.alternate+" TO "+f.role+" WITH "+tc.options)
			if tc.name == "set_only" {
				f.asLogin(t, "SET ROLE "+f.alternate)
				f.asLogin(t, "GRANT UPDATE ON pki_issuers TO "+f.alternate)
				f.asLogin(t, "REVOKE UPDATE ON pki_issuers FROM "+f.alternate)
				f.asLogin(t, "RESET ROLE")
			}
			f.rejected(t)
		})
	}
}
func TestCARoleRejectsSchemaOwnership(t *testing.T) {
	for _, viaSet := range []bool{false, true} {
		t.Run(map[bool]string{false: "direct", true: "set_role"}[viaSet], func(t *testing.T) {
			f := newCARoleFixture(t)
			owner := f.role
			if viaSet {
				owner = f.alternate
			}
			f.exec(t, "ALTER SCHEMA "+pgx.Identifier{f.schema}.Sanitize()+" OWNER TO "+owner)
			f.exec(t, "REVOKE CREATE ON SCHEMA "+pgx.Identifier{f.schema}.Sanitize()+" FROM "+owner)
			if viaSet {
				f.exec(t, "GRANT "+owner+" TO "+f.role+" WITH INHERIT FALSE, SET TRUE")
			}
			f.rejected(t)
		})
	}
}
