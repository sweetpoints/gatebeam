func TestIssuerImmutabilitySerialUniquenessAndRollback(t *testing.T) {
	p := testkit.Postgres(t)
	ctx := context.Background()
	tx := platformpg.NewRunner(p)
	store := New()
	registry := application.NewRegistry(tx, store)
	now := time.Now().UTC().Truncate(time.Second)
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	cert := &x509.Certificate{SerialNumber: big.NewInt(1), NotBefore: now, NotAfter: now.Add(time.Hour), IsCA: true, BasicConstraintsValid: true, KeyUsage: x509.KeyUsageCertSign}
	der, err := x509.CreateCertificate(rand.Reader, cert, cert, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	i := domain.Issuer{ID: "issuer-a", Fingerprint: "fingerprint-a", NotBefore: now, NotAfter: now.Add(time.Hour)}
	if e := registry.Register(ctx, i, der); e != nil {
		t.Fatal(e)
	}
	if e := registry.Register(ctx, i, der); e != nil {
		t.Fatal("idempotent register failed", e)
	}
	if e := registry.Register(ctx, i, []byte("different-der")); e == nil {
		t.Fatal("issuer overwritten")
	}
	reserve := func(serial domain.Serial) error {
		return tx.Within(ctx, func(sc transaction.Scope) error { return store.ReserveSerial(sc, i.ID, serial) })
	}
	if e := reserve("0000000000000000000000000000000000000001"); e != nil {
		t.Fatal(e)
	}
	if e := reserve("0000000000000000000000000000000000000001"); e == nil {
		t.Fatal("duplicate serial accepted")
	}
	for _, serial := range []domain.Serial{"00", "-1", "0", "ff", "0001", "8000000000000000000000000000000000000000"} {
		if e := reserve(serial); e == nil {
			t.Fatalf("invalid serial accepted: %s", serial)
		}
	}
	if e := tx.Within(ctx, func(sc transaction.Scope) error {
		if e := store.ReserveSerial(sc, i.ID, "0000000000000000000000000000000000000002"); e != nil {
			return e
		}
		return domain.ErrPolicy
	}); e == nil {
		t.Fatal("rollback error swallowed")
	}
	if e := reserve("0000000000000000000000000000000000000002"); e != nil {
		t.Fatal("reservation survived rollback", e)
	}
}

