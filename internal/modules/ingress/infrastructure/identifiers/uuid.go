// Package identifiers generates public UUIDs, independently of secret bearers.
package identifiers

import (
	"crypto/rand"
	"fmt"
)

type Generator struct{}

func (Generator) NewID() (string, error) {
	var b [16]byte
	if _, e := rand.Read(b[:]); e != nil {
		return "", e
	}
	b[6] = b[6]&15 | 64
	b[8] = b[8]&63 | 128
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[:4], b[4:6], b[6:8], b[8:10], b[10:]), nil
}
